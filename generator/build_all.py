def main() -> int:
    parser = argparse.ArgumentParser(description="Build Kamureii XDR GitHub Profile SVGs")
    parser.add_argument("--offline", action="store_true", help="Skip live GitHub API requests")
    parser.add_argument("--sync-readme", action="store_true", help="Rewrite README.md from config")
    parser.add_argument("--out-dir", default="assets/generated", help="Output directory for SVGs")
    args = parser.parse_args()

    repo_root = Path(__file__).resolve().parent.parent
    config_path = repo_root / "profile.config.yml"
    sigma_path = repo_root / "detections" / "kamureii_identity.sigma.yml"
    out_dir = repo_root / args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    config = yaml.safe_load(config_path.read_text(encoding="utf-8"))
    sigma_res = validate_sigma_file(sigma_path)
    if not sigma_res.passed:
        print("Sigma bio validation FAILED:", file=sys.stderr)
        for err in sigma_res.errors:
            print(f"  - {err}", file=sys.stderr)
        return 1

    scan = scan_github_hybrid(config, offline=args.offline)

    outputs: dict[str, str] = {
        "header-banner.svg": render_header_svg(config),
        "lineage-and-sigma.svg": render_lineage_sigma_svg(config, scan, sigma_res),
        "mitre-heatmap.svg": render_mitre_heatmap_svg(scan),
        "sysmon-feed.svg": render_sysmon_feed_svg(scan),
        "alert-console-static.svg": render_static_alert_console_svg(config),
        "action-escalate.svg": render_static_action_svg("escalate"),
        "action-benign.svg": render_static_action_svg("benign"),
        "action-isolate.svg": render_static_action_svg("isolate"),
        "canary-banner-static.svg": render_static_canary_svg(),
    }

    for filename, svg_content in outputs.items():
        (out_dir / filename).write_text(svg_content, encoding="utf-8")

    if args.sync_readme:
        readme_text = render_readme_markdown(config)
        (repo_root / "README.md").write_text(readme_text, encoding="utf-8")

    print(
        f"Generated {len(outputs)} v3 SVGs in {out_dir} "
        f"(live_github={scan.fetched_live}, repos={len(scan.repos)}, "
        f"mitre_mapped={len(scan.technique_tiers)}, sigma_valid={sigma_res.passed})"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
